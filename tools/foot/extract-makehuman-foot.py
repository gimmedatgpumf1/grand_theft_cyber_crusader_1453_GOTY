#!/usr/bin/env python3
"""Extract full-resolution CC0 MakeHuman feet; fitting must precede reduction.

Requires NumPy. Right feet can be reflected from these source meshes.
"""
from pathlib import Path
import argparse
import json
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'tools/human-source'
OUT=ROOT/'tools/foot'
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--original',action='store_true',help='extract the original foot with a higher ankle cut for the live preview')
args=parser.parse_args()

vertices=[]; body=[]; joints={}; group=''
for line in (SOURCE/'base.obj').read_text().splitlines():
    p=line.split()
    if not p: continue
    if p[0]=='v': vertices.append(list(map(float,p[1:4])))
    elif p[0]=='g': group=p[1]
    elif p[0]=='f':
        ids=[int(v.split('/')[0])-1 for v in p[1:]]
        if group=='body': body.append(ids)
        elif group.startswith('joint-l-'): joints.setdefault(group,set()).update(ids)
base=np.array(vertices,dtype=float)
weights=json.loads((SOURCE/'default_weights.mhw').read_text())['weights']
influences=[{} for _ in base]
for name, rows in weights.items():
    if name=='foot.L': code=0
    elif name.startswith('toe') and name.endswith('.L'):
        toe,segment=map(int,name[3:-2].split('-')); code=toe*10+segment
    else: continue
    for i,w in rows: influences[i][code]=w

def emit(sex):
    v=base.copy()
    for line in (SOURCE/f'caucasian-{sex}-young.target').read_text().splitlines():
        p=line.split()
        if len(p)==4 and p[0].isdigit(): v[int(p[0])]+=np.array(list(map(float,p[1:])))
    # Plane just above the ankle; clipping triangles gives one clean open rim.
    ankle=np.mean(v[list(joints['joint-l-ankle'])],axis=0)
    cut=ankle[1]+(.30 if args.original else .08)
    points=[]; faces=[]; labels=[]; lookup={}
    def vertex(key,p,label):
        if key not in lookup:
            lookup[key]=len(points);points.append(p);labels.append(label)
        return lookup[key]
    for poly in body:
        if min(v[i,0] for i in poly)<1: continue
        for j in range(1,len(poly)-1):
            ids=[poly[0],poly[j],poly[j+1]]; clipped=[]
            for a,b in zip(ids,ids[1:]+ids[:1]):
                pa,pb=v[a],v[b]; ina=pa[1]<=cut;inb=pb[1]<=cut
                if ina:
                    clipped.append(vertex(('v',a),pa,influences[a] or {0:1.0}))
                if ina!=inb:
                    t=(cut-pa[1])/(pb[1]-pa[1]); q=pa+(pb-pa)*t
                    key=('e',min(a,b),max(a,b))
                    clipped.append(vertex(key,q,{0:1.0}))
            for i in range(1,len(clipped)-1):faces.append([clipped[0],clipped[i],clipped[i+1]])
    points=np.array(points);faces=np.array(faces,dtype=np.int32)
    # joints are CC0 helper groups, not external landmark estimates.
    anchors=[]
    for toe in range(1,6):
        for j in range(1,4 if toe==1 else 5):
            anchors.append(np.mean(v[list(joints[f'joint-l-toe-{toe}-{j}'])],axis=0))
    anchors.append(ankle)
    print(sex, 'full-resolution',len(points),len(faces))
    return points,faces,labels,np.array(anchors)

for sex in ('male','female'):
    verts,faces,labels,anchors=emit(sex)
    symbol=('original'+sex.capitalize()) if args.original else sex
    out=['#pragma once','', '// Full-resolution CC0 source; generated by extract-makehuman-foot.py.',
         '#include "source-foot-type.h"','namespace gtc::native::makehuman_foot_data {']
    out+= [f'inline constexpr std::array<Vertex,{len(verts)}> {symbol}Vertices={{{{']
    def row(p,weights):
        x,y,z=p; ranked=sorted(weights.items(),key=lambda t:-t[1])[:4]
        scale=sum(w for _,w in ranked) or 1
        ranked += [(0,0.0)]*(4-len(ranked))
        owners=','.join(str(int(k)) for k,_ in ranked)
        amounts=','.join(f'{w/scale:.7f}f' for _,w in ranked)
        return f'{{{x:.7f}f,{y:.7f}f,{z:.7f}f,{ranked[0][0]},{{{{{owners}}}}},{{{{{amounts}}}}}}},'
    lines=[row(p,l) for p,l in zip(verts,labels)]
    out+= ['    '+''.join(lines[i:i+4]) for i in range(0,len(lines),4)]
    out+= ['}};',f'inline constexpr std::array<std::array<int,3>,{len(faces)}> {symbol}Faces={{{{']
    lines=[f'{{{{{a},{b},{c}}}}},' for a,b,c in faces]
    out+= ['    '+''.join(lines[i:i+6]) for i in range(0,len(lines),6)]
    out+= ['}};',f'inline constexpr std::array<std::array<float,3>,{len(anchors)}> {symbol}Anchors={{{{']
    out+= [f'    {{{{{x:.7f}f,{y:.7f}f,{z:.7f}f}}}},' for x,y,z in anchors]
    out+= ['}};','} // namespace gtc::native::makehuman_foot_data','']
    (OUT/f'{"original-foot" if args.original else "source-foot"}-{sex}.h').write_text('\n'.join(out))
