#!/usr/bin/env python3
"""Fit a shared rest-space correction to exported poses (experimental only).

The input must be generated by export-pose.cpp, including its blended skinning
matrices. Each pose is corrected in its own space, then its vertex displacement
is transformed back into the canonical left rest space. A successful run
checks every exported pose; it is not a guarantee for unexported poses.
"""
import argparse
import importlib.util
from pathlib import Path
import numpy as np
import trimesh
from scipy.spatial.distance import cdist

parser = argparse.ArgumentParser()
parser.add_argument('poses', type=Path)
parser.add_argument('sex', choices=('m', 'f'))
parser.add_argument('output', type=Path, help='canonical displacement file')
parser.add_argument('--initial', type=Path, help='existing displacement to refine')
parser.add_argument('--small-only', action='store_true', help='fit only 50 cm poses')
parser.add_argument('--ignore-ankle', action='store_true', help='initial fit against foot bones only')
parser.add_argument('--basic-only', action='store_true', help='fit rest and simultaneous bends only')
args = parser.parse_args()
spec = importlib.util.spec_from_file_location('clearance', Path(__file__).with_name('surface-clearance.py'))
clearance = importlib.util.module_from_spec(spec)
spec.loader.exec_module(clearance)
base = args.poses / (args.sex + '0_L-rest')
reference_length = float((base / 'skin-matrices.txt').read_text().splitlines()[0])
pattern = args.sex + ('50_*' if args.small_only else '*')
entries = []
for folder in sorted(args.poses.glob(pattern)):
    if not folder.is_dir() or (args.basic_only and '-toe' in folder.name):
        continue
    mesh = trimesh.load_mesh(folder / 'skin.obj', process=False)
    matrix = np.loadtxt(folder / 'skin-matrices.txt', skiprows=1).reshape(-1, 3, 3)
    length = float((folder / 'skin-matrices.txt').read_text().splitlines()[0])
    if len(matrix) != len(mesh.vertices):
        raise ValueError(f'{folder}: skin matrix count differs from vertex count')
    mirror = np.array([-1., 1., 1.]) if '_R-' in folder.name else np.ones(3)
    entries.append((folder.name, mesh, matrix, np.linalg.inv(matrix), length/reference_length,
                    mirror, clearance.load_bones(folder), [] if args.ignore_ankle else clearance.load_ankle_bones(folder)))
if not entries:
    raise ValueError('no pose directories')
count = len(entries[0][1].vertices)
delta = np.loadtxt(args.initial) if args.initial else np.zeros((count, 3))
if delta.shape != (count, 3):
    raise ValueError('incorrect initial displacement shape')

for iteration in range(35):
    max_move = 0.
    for name, mesh, matrix, inverse, scale, mirror, bones, ankle_bones in entries:
        original = mesh.vertices + np.einsum('nij,nj->ni', matrix, delta * mirror * scale)
        if clearance.clearance_valid(original, mesh.faces, bones, margin=.00013, ankle_bones=ankle_bones):
            continue
        posed = original.copy()
        points = np.concatenate([bone.vertices for _, bone in bones])
        radius = reference_length * scale * .025
        # Provide a well-behaved starting surface before solving exact contacts.
        for _ in range(30):
            outside = points[~clearance.closed_mesh(posed, mesh.faces).contains(points)]
            if not len(outside):
                break
            surface = trimesh.Trimesh(vertices=posed, faces=mesh.faces, process=False)
            closest, distances, _ = trimesh.proximity.closest_point(surface, outside)
            distance = cdist(posed, closest)
            weights = np.exp(-(distance / radius)**2 * 1.5)
            weights[distance > radius * 2] = 0
            vectors = (outside - closest) * (1 + .0002 / np.maximum(distances, 1e-9))[:, None]
            posed += .8 * (weights @ vectors) / np.maximum(weights.sum(axis=1), 1)[:, None]
        print(name, flush=True)
        fitted = clearance.fit_clearance(posed, mesh.faces, bones, margin=.00013, max_steps=70, ankle_bones=ankle_bones)
        correction = np.einsum('nij,nj->ni', inverse, fitted - original) * mirror / scale
        max_move = max(max_move, np.linalg.norm(correction, axis=1).max())
        delta += correction * .85
    print(f'pose pass {iteration}: max correction {max_move*1000:.4f} mm', flush=True)
    if max_move < 2e-8:
        np.savetxt(args.output, delta, fmt='%.15g')
        break
else:
    raise ValueError('pose clearance did not converge; no output was written')
