"""Export same-side game-mesh length ratios and published reference values.

Run from any directory with Python 3. Reads the PCA spans generated by
15-measure-bone-lengths.py. See BONE_RATIOS_README.md for references,
definitions and the important limitations of the mesh proxies.
"""
import csv
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
INPUT = BASE / 'BONE_LENGTH_MEASUREMENTS.csv'
OUTPUT = BASE / 'BONE_RATIOS.tsv'

# Pietak et al., Table 2, Asian Indian sex-specific means and SDs.
# Values are mean of individual ratios, not a ratio of group-average lengths.
REF = {
    'Humerus / Radius': ((1.30, .08), (1.30, .06)),
    'Humerus / Ulna': ((1.22, .09), (1.20, .06)),
    'Humerus / mean(Radius, Ulna)': ((1.26, .08), (1.25, .06)),
    'Femur / Tibia': ((1.21, .05), (1.19, .02)),
    'Femur / mean(Tibia, Fibula)': ((1.21, .05), (1.20, .02)),
    'Hand metacarpal 3 / proximal phalanx 3': ((1.50, .07), (1.50, .07)),
    'Hand metacarpal 3 / sum(phalanges 3)': ((.73, .04), (.74, .04)),
    'Hand proximal phalanx 3 / middle phalanx 3': ((1.56, .09), (1.58, .11)),
    'Hand middle phalanx 3 / distal phalanx 3': ((1.52, .13), (1.58, .16)),
    'Foot metatarsal 3 / proximal phalanx 3': ((2.57, .15), (2.70, .16)),
    'Foot metatarsal 3 / sum(phalanges 3)': ((1.45, .13), (1.50, .15)),
    'Foot proximal phalanx 3 / middle phalanx 3': ((2.45, .48), (2.49, .68)),
    'Foot middle phalanx 3 / distal phalanx 3': ((1.19, .22), (1.11, .22)),
    # Bogin & Varela-Silva, Table 1; published indices divided by 100.
    'Humerus / Femur': ((.714, None), (.698, None)),
    'sum(Humerus, Radius) / sum(Femur, Tibia)': ((.697, None), (.685, None)),
}


def specifications():
    # Name is the complete numerator/denominator, since a ratio needs both.
    specs = [
        ('Humerus / Radius', ('Humerus',), ('Radius',), 1),
        ('Humerus / Ulna', ('Humerus',), ('Ulna',), 1),
        ('Humerus / mean(Radius, Ulna)', ('Humerus',), ('Radius', 'Ulna'), 2),
        ('Femur / Tibia', ('Femur',), ('Tibia',), 1),
        ('Femur / mean(Tibia, Fibula)', ('Femur',), ('Tibia', 'Fibula'), 2),
        ('Radius / Ulna', ('Radius',), ('Ulna',), 1),
        ('Fibula / Tibia', ('Fibula',), ('Tibia',), 1),
        ('Humerus / Femur', ('Humerus',), ('Femur',), 1),
        ('sum(Humerus, Radius) / sum(Femur, Tibia)', ('Humerus', 'Radius'), ('Femur', 'Tibia'), 1),
    ]
    for area, metaname in [('Hand', 'metacarpal'), ('Foot', 'metatarsal')]:
        for d in range(1, 6):
            meta, prox, mid, dist = (f'{area}{part}{d}' for part in ('Meta', 'ProxP', 'MidP', 'DistP'))
            p, m, distal = (f'{part} phalanx {d}' for part in ('proximal', 'middle', 'distal'))
            common = f'{area} {metaname} {d}'
            phalanges = (prox, dist) if d == 1 else (prox, mid, dist)
            specs.append((f'{common} / {p}', (meta,), (prox,), 1))
            specs.append((f'{common} / sum(phalanges {d})', (meta,), phalanges, 1))
            if d == 1:
                specs.append((f'{area} {p} / {distal}', (prox,), (dist,), 1))
            else:
                specs.append((f'{area} {p} / {m}', (prox,), (mid,), 1))
                specs.append((f'{area} {m} / {distal}', (mid,), (dist,), 1))
    return specs


def main():
    with INPUT.open(newline='', encoding='utf-8') as source:
        rows = list(csv.DictReader(source))
    measured = {}
    for r in rows:
        key = (r['sex_label'], r['side'], r['bone'])
        if key in measured:
            raise ValueError(f'duplicate measurement: {key}')
        measured[key] = float(r['game_pca_span_mm'])
    specs = specifications()
    if len({s[0] for s in specs}) != len(specs) or not set(REF).issubset({s[0] for s in specs}):
        raise ValueError('duplicate or unused reference ratio')
    with OUTPUT.open('w', newline='', encoding='utf-8') as out:
        writer = csv.writer(out, delimiter='\t', lineterminator='\n')
        writer.writerow(['Bone name', 'Gender', 'L/R', 'Known biological ratio avg',
                         'Known biological ratio std', 'Measured ratio'])
        for name, numerator, denominator, divisor in specs:
            for sex_index, sex in enumerate(('male', 'female')):
                reference = REF.get(name, ((None, None), (None, None)))[sex_index]
                for side in ('L', 'R'):
                    num = sum(measured[(sex, side, b)] for b in numerator)
                    den = sum(measured[(sex, side, b)] for b in denominator) / divisor
                    if num <= 0 or den <= 0:
                        raise ValueError(f'invalid span for {name}, {sex}, {side}')
                    avg, sd = reference
                    writer.writerow([name, sex, side,
                                     '' if avg is None else f'{avg:.3f}',
                                     '' if sd is None else f'{sd:.3f}', f'{num/den:.4f}'])
    print(f'Wrote {OUTPUT} ({len(specs)*4} rows)')


if __name__ == '__main__':
    main()
