#!/usr/bin/env python3
"""Recompute sample SDs of the seven whole-body TSV columns, by sex.

No rows are removed: each column uses all its nonblank finite values. These
are pooled, unconditional SDs, not height-conditioned reference ranges.
"""
import csv
import math
import statistics
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[3]
folder = root / 'tools/skeleton-source/anthropometry'
columns = ['head_proxy_cm', 'neck_cm', 'torso_cm', 'arm_cm', 'leg_cm', 'pelvis_cm', 'shoulder_cm']
rows = []
for sex in ('male', 'female'):
    with (folder / f'{sex.upper()}_HEIGHT_DATA.tsv').open(newline='') as f:
        reader = csv.DictReader(f, delimiter='\t')
        if reader.fieldnames != ['height_cm', *columns]:
            raise ValueError(f'{sex}: unexpected columns')
        values = [[] for _ in columns]
        total = 0
        for row in reader:
            total += 1
            for i, column in enumerate(columns):
                if row[column].strip():
                    value = float(row[column])
                    if not math.isfinite(value):
                        raise ValueError(f'{sex}: non-finite {column} on row {total+1}')
                    values[i].append(value)
        for column, data in zip(columns, values):
            if len(data) < 2:
                raise ValueError(f'{sex}: insufficient {column} observations')
            rows.append((sex, column, total, len(data), statistics.mean(data), statistics.stdev(data)))

output = 'sex\tcolumn\ttotal_rows\tn_nonblank\tmean_cm\tsample_sd_cm\n'
for sex, column, total, n, mean, sd in rows:
    output += f'{sex}\t{column}\t{total}\t{n}\t{mean:.12f}\t{sd:.12f}\n'
header = '''#pragma once

#include <array>

namespace gtc::native {
// Generated by tools/skeleton-source/openskeleton/29-comparison-sd.py from
// the whole-body TSV columns. Unconditional sample SD, centimetres. The head
// and some child dimensions are estimates/proxies, not direct measurements.
inline constexpr std::array<double,7> maleComparisonSdCm{
'''
for sex in ('male', 'female'):
    vals = [row[5] for row in rows if row[0] == sex]
    if sex == 'female':
        header += '};\ninline constexpr std::array<double,7> femaleComparisonSdCm{\n'
    header += '    ' + ', '.join(f'{value:.12f}' for value in vals) + '\n'
header += '};\n} // namespace gtc::native\n'
files = {folder / 'BODY_SIZE_STANDARD_DEVIATIONS.tsv': output,
         root / 'native/client/comparison_standard_deviations.h': header}
for path, content in files.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'{path}: missing or stale')
    else:
        path.write_text(content)
print('Whole-body column sample SDs: PASS')
