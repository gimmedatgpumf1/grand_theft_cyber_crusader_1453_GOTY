#pragma once

// Exploratory *surface landmark* dimensions from paired surveys, in cm.
// This evaluates supplied data; it does not deform a skeleton, move joints,
// rebuild collision geometry, or establish clinical normality. See
// tools/skeleton-source/anthropometry/BODY_PART_CURVES.md before use.
#include "client/smooth_height_curve.h"
#include <algorithm>
#include <cmath>
#include <fstream>
#include <map>
#include <optional>
#include <sstream>
#include <string>
#include <tuple>
#include <vector>

namespace gtc::native {

class BodyProportionCurves {
public:
    struct Key {
        std::string source, sex, ageGroup, dimension;
        bool operator<(const Key& other) const {
            return std::tie(source,sex,ageGroup,dimension) <
                   std::tie(other.source,other.sex,other.ageGroup,other.dimension);
        }
    };
    // Transactional load: invalid files never replace previously valid curves.
    bool load(const std::string& path, std::string& error) {
        std::ifstream input(path);
        if (!input) { error="Cannot open body-part curves: "+path; return false; }
        std::string line;
        if (!std::getline(input,line)) { error="Empty body-part curves: "+path; return false; }
        stripCR(line);
        if (line!="source\tsex\tage_group\tdimension\tsource_column\tbin_start_cm\tn\theight_mean_cm\tdimension_mean_cm") {
            error="Invalid body-part curve header: "+path; return false;
        }
        std::map<Key,Curve> parsed;
        std::size_t lineNo=1;
        while (std::getline(input,line)) {
            ++lineNo; stripCR(line);
            std::istringstream row(line); std::vector<std::string> cells; std::string cell;
            while (std::getline(row,cell,'\t')) cells.push_back(cell);
            double start=0, count=0, x=0, y=0;
            if (cells.size()!=9 || cells[0].empty() || cells[1].empty() || cells[2].empty() ||
                cells[3].empty() || cells[4].empty() || !number(cells[5],start) ||
                !number(cells[6],count) || !number(cells[7],x) || !number(cells[8],y) ||
                count<20 || std::floor(count)!=count || x<start || x>=start+5 || y<=0 || x<=0) {
                error="Invalid body-part curve row "+std::to_string(lineNo); return false;
            }
            Key key{cells[0],cells[1],cells[2],cells[3]}; auto& curve=parsed[key];
            if (!curve.column.empty() && curve.column!=cells[4]) {
                error="Conflicting body-part measurement columns"; return false;
            }
            curve.column=cells[4]; curve.knots.push_back({x,y,start});
        }
        if (input.bad() || parsed.empty()) { error="Unable to read body-part curves: "+path; return false; }
        for (auto& pair:parsed) {
            auto& v=pair.second.knots;
            std::sort(v.begin(),v.end(),[](const Knot& a,const Knot& b){return a.x<b.x;});
            for (std::size_t i=1; i<v.size(); ++i) {
                if (v[i].x<=v[i-1].x || v[i].start<=v[i-1].start) {
                    error="Duplicate or unordered body-part curve bins"; return false;
                }
            }
        }
        curves_.swap(parsed); models_.clear(); smoothChildren_.clear(); error.clear(); return true;
    }

    // Load the per-dimension model choices generated by training-only CV.
    // All keys must match the currently loaded knot table. This does not alter
    // the skeleton or make the fitted models valid outside their support.
    bool loadSelectedModels(const std::string& path, std::string& error) {
        std::ifstream input(path); std::string line;
        if (!input || !std::getline(input,line)) { error="Cannot open selected models: "+path; return false; }
        stripCR(line);
        if (line!="source\tsex\tage_group\tdimension\tmethod\tcoef0\tcoef1\tcoef2") {
            error="Invalid selected model header: "+path; return false;
        }
        std::map<Key,Model> parsed; std::size_t lineNo=1;
        while (std::getline(input,line)) {
            ++lineNo; stripCR(line); std::istringstream row(line);
            std::vector<std::string> cells; std::string cell;
            while (std::getline(row,cell,'\t')) cells.push_back(cell);
            Model model;
            if (cells.size()!=8 || (cells[4]!="pchip" && cells[4]!="linear" && cells[4]!="quadratic" &&
                cells[4]!="log" && cells[4]!="power") || !number(cells[5],model.a) ||
                !number(cells[6],model.b) || !number(cells[7],model.c)) {
                error="Invalid selected model row "+std::to_string(lineNo); return false;
            }
            Key key{cells[0],cells[1],cells[2],cells[3]}; model.method=cells[4];
            if (curves_.find(key)==curves_.end() || !parsed.emplace(key,model).second) {
                error="Unknown or duplicate selected model"; return false;
            }
        }
        if (input.bad() || parsed.empty()) { error="Unable to read selected models: "+path; return false; }
        // Retain the selected empirical models unchanged. The transition uses
        // a C2 approximation sampled from each child model; build it once here
        // so dragging the slider does not repeatedly refit data.
        models_.swap(parsed);
        std::map<Key,SmoothHeightCurve> smoothed;
        for (const std::string sex:{"male","female"})
            for (const std::string dim:{"sitting_height","upper_arm_surface","upper_leg_surface",
                                         "shoulder_breadth","pelvis_surface_breadth"}) {
                const Key child{"NHANES_III",sex,"under_18",dim};
                if (models_.find(child)==models_.end()) continue;
                SmoothHeightCurve curve;
                const double high=sex=="male" ? 190.0 : 175.0;
                if (!curve.build(high,[&](double h){return selectedDimensionCm(child,h);})) {
                    models_.swap(parsed); error="Cannot construct smooth child reference"; return false;
                }
                smoothed.emplace(child,std::move(curve));
            }
        smoothChildren_.swap(smoothed); error.clear(); return true;
    }

    // Outside the observed knot range use a smooth, bounded continuation,
    // not the selected family's unchecked extrapolation. Such results are
    // estimates, not measurements or validated biological predictions.
    std::optional<double> selectedDimensionCm(const Key& key, double heightCm) const {
        if (!std::isfinite(heightCm) || heightCm<=0) return std::nullopt;
        const auto curve=curves_.find(key);
        const auto it=models_.find(key);
        if (curve==curves_.end() || it==models_.end()) return std::nullopt;
        if (key.dimension=="height_minus_sitting") {
            Key sitting=key; sitting.dimension="sitting_height";
            const auto value=selectedDimensionCm(sitting,heightCm);
            if (!value || *value>=heightCm) return std::nullopt;
            return heightCm-*value;
        }
        const auto& m=it->second;
        const auto& knots=curve->second.knots;
        if (m.method=="pchip") return dimensionCm(key,heightCm);
        const double x=std::clamp(heightCm,knots.front().x,knots.back().x);
        const double z=x-150.0; double result=0, slope=0, curvature=0;
        if (m.method=="linear") { result=m.a+m.b*z; slope=m.b; }
        else if (m.method=="quadratic") { result=m.a+m.b*z+m.c*z*z; slope=m.b+2*m.c*z; curvature=2*m.c; }
        else if (m.method=="log") { result=m.a+m.b*std::log(x/150.0); slope=m.b/x; curvature=-m.b/(x*x); }
        else if (m.method=="power") { result=m.a*std::pow(x/150.0,m.b); slope=m.b*result/x;
                                       curvature=m.b*(m.b-1)*result/(x*x); }
        if (x!=heightCm) return smoothBoundedContinuation(heightCm,x,result,slope,curvature);
        if (!std::isfinite(result) || result<=0 || result>=heightCm) return std::nullopt;
        return result;
    }

    // Height-only transition between NHANES III child and adult *surface*
    // models with matching landmarks. This is a modelling convention, not an
    // inference of age from stature. All dimensions share a broad, smooth
    // transition rather than concentrating the age-group differences into a
    // short height interval. Outside the sampled ranges, smooth continuation
    // is an unvalidated estimate rather than observed evidence.
    std::optional<double> blendedNhanesDimensionCm(const std::string& sex,
                                                  const std::string& dimension,
                                                  double heightCm) const {
        if (!std::isfinite(heightCm) || heightCm<=0 || (sex!="male" && sex!="female")) return std::nullopt;
        if (dimension!="sitting_height" && dimension!="height_minus_sitting" &&
            dimension!="upper_arm_surface" && dimension!="upper_leg_surface" &&
            dimension!="shoulder_breadth" && dimension!="pelvis_surface_breadth") return std::nullopt;
        if (dimension=="height_minus_sitting") {
            const auto sitting=blendedNhanesDimensionCm(sex,"sitting_height",heightCm);
            if (!sitting || *sitting>=heightCm) return std::nullopt;
            return heightCm-*sitting;
        }
        const Key child{"NHANES_III",sex,"under_18",dimension};
        const Key adult{"NHANES_III",sex,"adult_18_plus",dimension};
        const auto smooth=smoothChildren_.find(child);
        if (smooth==smoothChildren_.end() || models_.find(adult)==models_.end()) return std::nullopt;
        // Neonatal surface anchors come from several studies, not one subject;
        // crown-rump is only an approximation to sitting height. See the
        // extrapolation report for definitions and limitations.
        double infantRatio=0;
        if (dimension=="sitting_height") infantRatio=sex=="male" ? 34.2/50.9 : 33.7/50.4;
        else if (dimension=="upper_arm_surface") infantRatio=sex=="male" ? 0.1900 : 0.1908;
        else if (dimension=="upper_leg_surface") infantRatio=8.3/50.6;
        else if (dimension=="shoulder_breadth") infantRatio=12.4/50.0;
        else if (dimension=="pelvis_surface_breadth") infantRatio=7.74/48.75;
        const double infant=heightCm*infantRatio;
        if (heightCm<=50) return infant;
        if (heightCm<100) {
            // Quintic Hermite matches value, slope and curvature at both
            // ends. Infant and child inputs are still different populations.
            const auto end=smooth->second.evaluate(100);
            if (!end) return std::nullopt;
            const double t=(heightCm-50)/50, t2=t*t, t3=t2*t, t4=t3*t, t5=t4*t;
            const double h00=1-10*t3+15*t4-6*t5, h10=t-6*t3+8*t4-3*t5;
            const double h01=10*t3-15*t4+6*t5, h11=-4*t3+7*t4-3*t5;
            const double h21=(t3-2*t4+t5)*0.5;
            return h00*50*infantRatio+h10*50*infantRatio+h01*end->value+
                   h11*50*end->slope+h21*2500*end->curvature;
        }
        // The child and adult surfaces differ at the same stature. Squeezing
        // that difference into 15 cm caused a visible change in growth rate,
        // especially in the shoulder frame and arms. Spread the blend across
        // the same broad range for all dimensions. Adult continuation at low
        // height is an interpolation assumption, not an age estimate.
        const double low=100.0, high=sex=="male" ? 190.0 : 175.0;
        if (heightCm<=low) {
            const auto c=smooth->second.evaluate(low);
            return c ? std::optional<double>(c->value) : std::nullopt;
        }
        if (heightCm>=high) return selectedDimensionCm(adult,heightCm);
        const auto c=smooth->second.evaluate(heightCm);
        const auto a=selectedDimensionCm(adult,heightCm);
        if (!c || !a) return std::nullopt;
        return mix(c->value,*a,(heightCm-low)/(high-low));
    }

    // A dimensionless multiplier relative to a specified source stature.
    // Surface ratios are not yet calibrated skeletal or collision scales.
    std::optional<double> blendedNhanesScale(const std::string& sex,
                                             const std::string& dimension,
                                             double heightCm, double referenceHeightCm) const {
        const auto target=blendedNhanesDimensionCm(sex,dimension,heightCm);
        const auto reference=blendedNhanesDimensionCm(sex,dimension,referenceHeightCm);
        if (!target || !reference || *reference<=0) return std::nullopt;
        const double scale=*target / *reference;
        return std::isfinite(scale) && scale>0 ? std::optional<double>(scale) : std::nullopt;
    }

    // PCHIP interpolates across knots, even sparse gaps. Outside the measured
    // range a curvature-matched bounded-fraction continuation avoids hard height
    // cutoffs. These are surface dimensions, not bone lengths, and neither
    // sparse gaps nor extrapolation are validated by the underlying data.
    std::optional<double> dimensionCm(const Key& key, double heightCm) const {
        if (!std::isfinite(heightCm) || heightCm<=0) return std::nullopt;
        const auto found=curves_.find(key);
        if (found==curves_.end()) return std::nullopt;
        // This is defined as height minus sitting height, not an independent
        // bone measurement; preserve that identity between interpolation knots.
        if (key.dimension=="height_minus_sitting") {
            Key sitting=key; sitting.dimension="sitting_height";
            const auto value=dimensionCm(sitting,heightCm);
            if (!value || *value>=heightCm) return std::nullopt;
            return heightCm-*value;
        }
        const auto& v=found->second.knots;
        auto upper=std::lower_bound(v.begin(),v.end(),heightCm,
            [](const Knot& knot,double x){return knot.x<x;});
        if (upper!=v.end() && upper->x==heightCm) return upper->y;
        if (upper==v.begin() || upper==v.end()) {
            const std::size_t i=upper==v.begin() ? 0 : v.size()-1;
            const double slope=v.size()==1 ? v[i].y/v[i].x : derivative(v,i);
            const double curvature=v.size()==1 ? 0 : endpointCurvature(v,i==0);
            return smoothBoundedContinuation(heightCm,v[i].x,v[i].y,slope,curvature);
        }
        const std::size_t j=static_cast<std::size_t>(upper-v.begin()), i=j-1;
        const double h=v[j].x-v[i].x;
        const double t=(heightCm-v[i].x)/h, t2=t*t, t3=t2*t;
        const double value=(2*t3-3*t2+1)*v[i].y+(t3-2*t2+t)*h*derivative(v,i)+
                           (-2*t3+3*t2)*v[j].y+(t3-t2)*h*derivative(v,j);
        return std::isfinite(value) && value>0 ? std::optional<double>(value) : std::nullopt;
    }
private:
    struct Knot { double x,y,start; };
    struct Curve { std::string column; std::vector<Knot> knots; };
    struct Model { std::string method; double a=0,b=0,c=0; };
    std::map<Key,Curve> curves_;
    std::map<Key,Model> models_;
    std::map<Key,SmoothHeightCurve> smoothChildren_;
    static double mix(double first,double second,double t) {
        const double weight=t*t*t*(10.0+t*(-15.0+6.0*t));
        return first+weight*(second-first);
    }
    // One-sided curvature of the endpoint PCHIP segment. This lets the
    // bounded continuation join the selected curve through second derivative.
    static double endpointCurvature(const std::vector<Knot>& knots,bool first) {
        const std::size_t i=first ? 0 : knots.size()-2;
        const double width=knots[i+1].x-knots[i].x;
        const double sec=(knots[i+1].y-knots[i].y)/width;
        const double a=derivative(knots,i), b=derivative(knots,i+1);
        return first ? (6*sec-4*a-2*b)/width : (-6*sec+2*a+4*b)/width;
    }
    static void stripCR(std::string& line) { if (!line.empty() && line.back()=='\r') line.pop_back(); }
    static bool number(const std::string& text,double& value) {
        try { std::size_t end=0; value=std::stod(text,&end); return end==text.size() && std::isfinite(value); }
        catch (...) { return false; }
    }
    static double secant(const Knot& a,const Knot& b) { return (b.y-a.y)/(b.x-a.x); }
    static double endpoint(double h0,double h1,double m0,double m1) {
        double d=((2*h0+h1)*m0-h0*m1)/(h0+h1);
        if (d*m0<=0) return 0;
        if (m0*m1<0 && std::abs(d)>3*std::abs(m0)) return 3*m0;
        return d;
    }
    // Fritsch-Butland monotonicity-preserving cubic Hermite derivatives,
    // matching scipy.interpolate.PchipInterpolator for the same knots.
    static double derivative(const std::vector<Knot>& v,std::size_t i) {
        const auto n=v.size();
        if (n==2) return secant(v[0],v[1]);
        if (i==0) return endpoint(v[1].x-v[0].x,v[2].x-v[1].x,
                                  secant(v[0],v[1]),secant(v[1],v[2]));
        if (i==n-1) return endpoint(v[n-1].x-v[n-2].x,v[n-2].x-v[n-3].x,
                                    secant(v[n-2],v[n-1]),secant(v[n-3],v[n-2]));
        const double left=secant(v[i-1],v[i]), right=secant(v[i],v[i+1]);
        if (left*right<=0) return 0;
        const double before=v[i].x-v[i-1].x, after=v[i+1].x-v[i].x;
        const double w1=2*after+before, w2=after+2*before;
        return (w1+w2)/(w1/left+w2/right);
    }
};

} // namespace gtc::native
