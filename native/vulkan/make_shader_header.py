#!/usr/bin/env python3
"""Turn the compiled SPIR-V modules into the header the renderer links against.

The shaders are real GLSL (``shaders/*.vert``, ``shaders/*.frag``) compiled with
the Khronos reference compiler:

    glslangValidator -V --target-env vulkan1.0 -o shaders/skeleton.vert.spv shaders/skeleton.vert
    glslangValidator -V --target-env vulkan1.0 -DNO_UV=1 -o shaders/skeleton_no_uv.vert.spv shaders/skeleton.vert
    glslangValidator -V --target-env vulkan1.0 -o shaders/skeleton.frag.spv shaders/skeleton.frag

and then checked with the Khronos validator:

    spirv-val --target-env vulkan1.0 shaders/skeleton.vert.spv

Neither tool is needed to build the client: the ``.spv`` files and this header
are committed, so a machine with only a C++ compiler still builds. This script
only has to be re-run after a shader changes.

    python3 native/vulkan/make_shader_header.py --write
    python3 native/vulkan/make_shader_header.py --check   # what the tests run
"""

import argparse
import pathlib
import struct
import sys

# Module file name -> the C++ identifier it becomes.
MODULES = (
    ('skeleton.vert.spv', 'skeleton_vert'),
    ('skeleton_no_uv.vert.spv', 'skeleton_no_uv_vert'),
    ('skeleton.frag.spv', 'skeleton_frag'),
)

HERE = pathlib.Path(__file__).resolve().parent
SHADERS = HERE / 'shaders'
HEADER = SHADERS / 'spirv_shaders.h'


def words(path):
    """The module as 32-bit words, refusing anything that is not a module."""
    raw = path.read_bytes()
    if len(raw) % 4:
        raise SystemExit(f'{path.name}: {len(raw)} bytes is not a whole number of words')
    values = list(struct.unpack(f'<{len(raw) // 4}I', raw))
    if not values or values[0] != 0x07230203:
        raise SystemExit(f'{path.name}: not a SPIR-V module (bad magic)')
    return values


def render():
    text = ['// Generated by native/vulkan/make_shader_header.py -- do not edit by hand.',
            '//',
            '// The modules are compiled from shaders/*.vert and shaders/*.frag by the',
            '// Khronos reference compiler and validated with spirv-val; see the script.',
            '#pragma once',
            '#include <cstdint>',
            '',
            'namespace gtc::native::vk::spirv {',
            '']
    for name, symbol in MODULES:
        module = words(SHADERS / name)
        text.append(f'// {name}: {len(module)} words')
        text.append(f'inline constexpr std::uint32_t {symbol}[] = {{')
        for start in range(0, len(module), 6):
            chunk = ', '.join(f'0x{value:08x}u' for value in module[start:start + 6])
            text.append(f'    {chunk},')
        text.append('};')
        text.append('')
    text.append('} // namespace gtc::native::vk::spirv')
    text.append('')
    return '\n'.join(text)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true', help='regenerate spirv_shaders.h')
    parser.add_argument('--check', action='store_true',
                        help='fail if the header is not what the .spv files say')
    arguments = parser.parse_args()
    for name, _ in MODULES:
        if not (SHADERS / name).exists():
            raise SystemExit(f'missing {name}: compile the GLSL in native/vulkan/shaders first')
    expected = render()
    if arguments.write:
        HEADER.write_text(expected)
        print(f'wrote {HEADER.relative_to(HERE.parent.parent)}')
    if arguments.check:
        if not HEADER.exists() or HEADER.read_text() != expected:
            print('spirv_shaders.h is out of date -- run make_shader_header.py --write',
                  file=sys.stderr)
            raise SystemExit(1)
        counts = ', '.join(f'{name} {len(words(SHADERS / name))} words' for name, _ in MODULES)
        print(f'shaders match the header ({counts})')
    if not arguments.write and not arguments.check:
        print(expected)


if __name__ == '__main__':
    main()
